//! A library in a Zephyr application: as a module of its own, with a block in the application's CMakeLists.txt and in its
//! Kconfig file, and what the zephyr section of its libnima.yml says goes where.
//!
//! Under project, the application's own files: conf, the library's block in prj.conf, beside its switch; sysbuild, its
//! block in sysbuild.conf; and cmake, its blocks in CMakeLists.txt, under before-zephyr and after-zephyr. Under library,
//! its own folder: kconfig, the defaults of its Kconfig; conf, its Kconfig fragment, zephyr/<name>.conf, which a block of
//! the application's CMakeLists.txt adds to EXTRA_CONF_FILE, read after prj.conf; and cmake, the lines of its own
//! CMakeLists.txt.

mod common;

use std::fs;
use std::path::{Path, PathBuf};

use common::{Watched, ZEPHYR_CMAKELISTS, backups, put, read, record, run_with, write};
use libnima_core::flow::{self, Request};
use libnima_core::manifest::{self, Manifest};
use libnima_core::platform::zephyr::{app, module};
use libnima_core::platform::{Platform, PlatformArgs, target_of};
use libnima_core::target::Level;

const STARS: &str =
    "# ******************************************************************************";

const OPEN: &str = "# >>> libnima: gcore >>>\n# Added by libnima, and written again on every install, so set\n# gcore's settings below this block rather than in it.\n";
const CLOSE: &str = "# <<< libnima: gcore <<<\n";

const HEADER: &str = "# Generated by libnima for gcore 1.2.0. Written again on\n# every install and update, so a change made here does not last.\n#\n# gcore's settings, from zephyr.library.conf in its libnima.yml. The\n# application's CMakeLists.txt adds this file to EXTRA_CONF_FILE, so Zephyr\n# reads it after prj.conf, and a line here wins over one there.\n\n";

const CONF: &str = "      - BT_AUTO_PHY_PERIPHERAL_2M\n      - CONFIG_BT_CTLR_SDC_MAX_CONN_EVENT_LEN_DEFAULT=4000000\n      - 'BT_DEVICE_NAME=\"gcore\"'\n      - NCS_MCUBOOT_IMGTOOL_SET_ROM_FIXED_ADDRESS=n\n";
const LINES: &str = "CONFIG_BT_AUTO_PHY_PERIPHERAL_2M=y\nCONFIG_BT_CTLR_SDC_MAX_CONN_EVENT_LEN_DEFAULT=4000000\nCONFIG_BT_DEVICE_NAME=\"gcore\"\nCONFIG_NCS_MCUBOOT_IMGTOOL_SET_ROM_FIXED_ADDRESS=n\n";

const FRAGMENT_BLOCK: &str = "# >>> libnima: gcore/zephyr.conf >>>\n# gcore's Kconfig settings, from zephyr.library.conf in its libnima.yml,\n# read after prj.conf. Written again on every install.\nlist(APPEND EXTRA_CONF_FILE \"${CMAKE_CURRENT_SOURCE_DIR}/modules/gcore/zephyr/gcore.conf\")\n# <<< libnima: gcore/zephyr.conf <<<\n";

/// The switch, last in the block of prj.conf, a group of its own under the library's name.
fn switch() -> String {
    format!("{STARS}\n# gcore\n{STARS}\nCONFIG_GCORE=y\n")
}

/// gcore's block in prj.conf: its lines, plain, then the switch, after a blank line each.
fn block_of(lines: &[&str]) -> String {
    let body: String = lines.iter().map(|line| format!("{line}\n")).collect();
    let gap = if body.is_empty() { "" } else { "\n" };

    format!("{OPEN}\n{body}{gap}{}{CLOSE}", switch())
}

fn offline() -> libnima_core::download::Client {
    common::Github::serving(&[]).client()
}

/// A library in a folder of its own, with what its libnima.yml says around its name, its code and its platform.
fn lib_at(root: &Path, name: &str, body: &str, files: &[(&str, &str)]) -> PathBuf {
    let folder = root.join(name);

    put(
        &folder,
        &[
            (
                &format!("src/{name}.h"),
                &format!("/**\n * @version 1.2.0\n */\nint {name}_answer(void);\n"),
            ),
            (
                &format!("src/{name}.c"),
                "int answer(void) { return 42; }\n",
            ),
        ],
    );
    put(&folder, files);
    fs::write(
        folder.join("libnima.yml"),
        format!(
            "name: {name}\ndescription: A library for the tests\nrepository: https://github.com/someone/{name}\nplatform: zephyr\nheaders:\n  - src/{name}.h\nsources:\n  - src/{name}.c\n{body}"
        ),
    )
    .unwrap();

    folder
}

fn demo(root: &Path, body: &str) -> PathBuf {
    lib_at(root, "demo", body, &[])
}

/// gcore, with its switch, and what it writes given in its zephyr section.
fn gcore(root: &Path, zephyr: &str) -> PathBuf {
    gcore_with(root, zephyr, "", &[])
}

fn gcore_with(root: &Path, zephyr: &str, more: &str, files: &[(&str, &str)]) -> PathBuf {
    lib_at(
        root,
        "gcore",
        &format!("zephyr:\n  symbol: GCORE\n{zephyr}{more}"),
        files,
    )
}

fn read_it(folder: &Path) -> Result<Manifest, String> {
    manifest::load(folder, Some(Platform::Zephyr)).map_err(|error| error.message)
}

/// Why this zephyr section is refused.
fn refused(zephyr: &str) -> String {
    let root = tempfile::tempdir().unwrap();

    read_it(&gcore(root.path(), zephyr)).unwrap_err()
}

fn loaded(zephyr: &str) -> Manifest {
    let root = tempfile::tempdir().unwrap();

    read_it(&gcore(root.path(), zephyr)).unwrap()
}

/// An application on disk.
fn application(root: &Path, prj: Option<&str>, files: &[(&str, &str)], crlf: bool) -> PathBuf {
    application_named(root, "app", ZEPHYR_CMAKELISTS, prj, files, crlf)
}

fn application_named(
    root: &Path,
    name: &str,
    cmake: &str,
    prj: Option<&str>,
    files: &[(&str, &str)],
    crlf: bool,
) -> PathBuf {
    let project = root.join(name);
    let mut all: Vec<(&str, &str)> = vec![
        ("CMakeLists.txt", cmake),
        ("src/main.c", "int main(void) { return 0; }\n"),
    ];

    if let Some(prj) = prj {
        all.push(("prj.conf", prj));
    }

    all.extend_from_slice(files);

    for (file, text) in all {
        write(
            project.join(file),
            &if crlf {
                text.replace('\n', "\r\n")
            } else {
                text.to_string()
            },
        );
    }

    project
}

fn plain_app(root: &Path) -> PathBuf {
    application(root, Some("CONFIG_GPIO=y\n"), &[], false)
}

fn asked(project: &Path, library: &Path, folder: Option<&str>) -> Request {
    let mut asked = common::request(project, &[library]);

    asked.folder = folder.map(str::to_string);

    asked
}

fn run(asked: &Request) -> (i32, Watched) {
    run_with(offline(), asked)
}

/// Install, nobody at the keyboard, into modules/<name> as it is offered.
fn install(project: &Path, library: &Path) -> Watched {
    let (code, ui) = run(&asked(project, library, None));

    assert_eq!(code, 0, "{}\n{}", ui.out(), ui.err());

    ui
}

fn uninstall(project: &Path, name: &str) -> Watched {
    let (code, ui) = run(&Request {
        uninstall: vec![name.to_string()],
        project: Some(project.to_path_buf()),
        ..Request::default()
    });

    assert_eq!(code, 0, "{}\n{}", ui.out(), ui.err());

    ui
}

fn in_module(project: &Path, library: &str, file: &str) -> PathBuf {
    project
        .join("modules")
        .join(library)
        .join("zephyr")
        .join(file)
}

fn snapshot(project: &Path, names: &[&str]) -> Vec<String> {
    names.iter().map(|name| read(project.join(name))).collect()
}

fn all_backups(project: &Path) -> Vec<String> {
    libnima_core::paths::files_below(project)
        .into_iter()
        .filter(|path| path.ends_with(".bak"))
        .collect()
}

fn position(text: &str, wanted: &str) -> usize {
    text.find(wanted)
        .unwrap_or_else(|| panic!("{wanted} is not in:\n{text}"))
}

