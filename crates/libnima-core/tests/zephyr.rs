#[test]
fn what_the_user_set_is_not_set_again() {
    // A later line wins in Kconfig, so the block would quietly undo the user's choice.
    let root = tempfile::tempdir().unwrap();
    let project = application(
        root.path(),
        Some("CONFIG_I2C=n\n# CONFIG_LOG is not set\nCONFIG_GCORE=n\n"),
        &[],
        true,
    );

    install(
        &project,
        &gcore(
            root.path(),
            "  project:\n    conf:\n      - I2C\n      - LOG\n      - GPIO\n",
        ),
    );

    let text = read(project.join("prj.conf"));
    let block = &text[position(&text, "# >>>")..];

    // Written, but commented out, saying who sets it: the block shows what the library asked for, and Kconfig reads none
    // of it.
    assert!(
        block.contains("# CONFIG_I2C=y  (left out: prj.conf sets CONFIG_I2C=n)"),
        "{block}"
    );
    assert!(
        block.contains("# CONFIG_LOG=y  (left out: prj.conf sets CONFIG_LOG=n)"),
        "{block}"
    );
    assert!(
        block.contains("# CONFIG_GCORE=y  (left out: prj.conf sets CONFIG_GCORE=n)"),
        "{block}"
    );

    let set: Vec<String> = libnima_core::platform::kconfig::ASSIGNED
        .captures_iter(block)
        .map(|found| found[1].to_string())
        .collect();

    assert_eq!(set, ["GPIO"]);
    assert!(!libnima_core::platform::kconfig::NOT_SET.is_match(block));
}

