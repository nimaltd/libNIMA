    install(&project, &second);

    let path = project.join("CMakeLists.txt");
    let text = read(&path);
    let gled = text[position(&text, "# >>> libnima: gled/zephyr.conf >>>")..]
        .split_inclusive('\n')
        .take(5)
        .collect::<String>();
