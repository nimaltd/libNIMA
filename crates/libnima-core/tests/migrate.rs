//! A project lib-installer, or one of the five installers before it, installed into, moved over on the first run: its
//! record, and the markers of its blocks in the project's files. Each project here is made by libNIMA, then turned back
//! into what was there before, the way a user's project is.

mod common;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use common::*;
use libnima_core::flow::Request;
use libnima_core::installer::migrate;
use libnima_core::platform::{Platform, PlatformArgs, target_of};
use regex::Regex;
use serde_json::Value;

const DEFINE: &str = "defines:\n  - DEMO_SIZE=8\n";

/// Every file under roots, but the backups.
fn files(roots: &[&Path]) -> Vec<PathBuf> {
    let mut found = Vec::new();

    for root in roots {
        for path in libnima_core::paths::files_below(root) {
            if !path.ends_with(".bak") {
                found.push(root.join(path));
            }
        }
    }

    found
}

/// Make what libNIMA wrote under roots what `legacy` wrote: its record, the markers of its blocks, and the first line of
/// the files it generates. What is inside each block stays as it is, as it would after an update.
fn downgrade(legacy: &str, roots: &[&Path]) {
    let markers = Regex::new(r"(?m)^([ \t]*[#;][ \t]*)(>>>|<<<) libnima: ").unwrap();

    for path in files(roots) {
        if path.file_name().unwrap() == ".libnima.json" {
            let mut data: Value = serde_json::from_str(&read(&path)).unwrap();

            // The record of the installer of one platform did not say which it was.
            if legacy != "lib-installer" {
                data.as_object_mut().unwrap().remove("platform");
                data["record"] = Value::from(2);
            }

            write(
                path.with_file_name(format!(".{legacy}.json")),
                &data.to_string(),
            );
            fs::remove_file(path).unwrap();

            continue;
        }

        let Ok(text) = String::from_utf8(fs::read(&path).unwrap()) else {
            continue;
        };
        let old = markers.replace_all(&text, |found: &regex::Captures| {
            format!("{}{} {legacy}: ", &found[1], &found[2])
        });
        let old = old.replace(
            "# Generated by libnima",
            &format!("# Generated by {legacy}"),
        );

        if old != text {
            fs::write(&path, old).unwrap();
        }
    }
}

/// {file: the text of every marker line in it}, for every file with one.
fn marked(roots: &[&Path]) -> BTreeMap<PathBuf, Vec<String>> {
    let marker = Regex::new(r"^[ \t]*[#;][ \t]*(>>>|<<<) ").unwrap();
    let mut found = BTreeMap::new();

    for path in files(roots) {
        let text = String::from_utf8_lossy(&fs::read(&path).unwrap()).into_owned();
        let lines: Vec<String> = text
            .lines()
            .filter(|line| marker.is_match(line))
            .map(str::to_string)
            .collect();

        if !lines.is_empty() {
            found.insert(path, lines);
        }
    }

    found
}

fn offline() -> libnima_core::download::Client {
    Github::serving(&[]).client()
}

fn run(asked: &Request) -> (i32, Watched) {
    run_with(offline(), asked)
}

/// A run putting a library in a project of its platform, outside components on ESP-IDF, so it has a block in the
/// project's CMakeLists.txt.
fn asked_for(project: &Path, source: &Path, platform: &str) -> Request {
    let mut asked = request(project, &[source]);

    if platform == "esp32" {
        asked.folder = Some("libs/demo".to_string());
    }

    asked
}

fn holds_file(folder: &Path, name: &str) -> bool {
    !backups(folder, name).is_empty()
}

fn record_file(folder: &Path) -> Value {
    serde_json::from_str(&read(folder.join(".libnima.json"))).unwrap()
}

#[test]
fn a_project_of_what_came_before_moves_over() {
    for platform in ["stm32", "zephyr", "esp32", "pio"] {
        for crlf in [false, true] {
            for legacy in ["lib-installer".to_string(), format!("{platform}-installer")] {
                let root = tempfile::tempdir().unwrap();
                let project = project_of(root.path(), platform, &[], crlf);
                let source = library_of(root.path(), "demo", platform, DEFINE);
                let asked = asked_for(&project, &source, platform);
                let (code, ui) = run(&asked);

                assert_eq!(code, 0, "{platform}: {}", ui.err());

                let written: BTreeMap<PathBuf, Vec<u8>> = files(&[&project])
                    .into_iter()
                    .map(|path| (path.clone(), fs::read(path).unwrap()))
                    .collect();
                let markers = marked(&[&project]);

                assert!(!markers.is_empty(), "{platform}");
                downgrade(&legacy, &[&project]);

                let (code, ui) = run(&asked);
                let kept = record_file(&project);

                assert_eq!(code, 0, "{platform}: {}", ui.err());
                assert!(
                    ui.out()
                        .contains(&format!("Moved over from {legacy} to libnima")),
                    "{}",
                    ui.out()
                );
                assert_eq!(kept["platform"], platform);
                assert_eq!(
                    kept["libraries"]
                        .as_object()
                        .unwrap()
                        .keys()
                        .collect::<Vec<_>>(),
                    ["demo"]
                );
                assert!(!project.join(format!(".{legacy}.json")).exists());
                assert!(
                    holds_file(&project, &format!(".{legacy}.json")),
                    "{platform}: the old record was not kept"
                );

                // One block of each, where it was, and nothing of the old name: not a second block beside the old one.
                assert_eq!(marked(&[&project]), markers, "{platform} {legacy}");

                // Each file the markers moved in was saved first.
                for path in markers.keys() {
                    let name = path.file_name().unwrap().to_string_lossy();

                    assert!(
                        holds_file(path.parent().unwrap(), &name),
                        "{}",
                        path.display()
                    );
                }

                for path in files(&[&project]) {
                    let text = String::from_utf8_lossy(&fs::read(&path).unwrap()).into_owned();

                    assert!(
                        !text.contains(&legacy),
                        "{legacy} is still in {}",
                        path.display()
                    );
                }

                for (path, before) in &written {
                    if path.file_name().unwrap() != ".libnima.json" {
                        assert_eq!(
                            &fs::read(path).unwrap(),
                            before,
                            "{} changed",
                            path.display()
                        );
                    }
                }
            }
        }
    }
}

#[test]
fn an_uninstall_takes_out_what_came_before_wrote() {
    for platform in ["stm32", "zephyr", "esp32", "pio"] {
        for legacy in ["lib-installer".to_string(), format!("{platform}-installer")] {
            let root = tempfile::tempdir().unwrap();
            let project = project_of(root.path(), platform, &[], false);
            let source = library_of(root.path(), "demo", platform, DEFINE);
            let (code, ui) = run(&asked_for(&project, &source, platform));

            assert_eq!(code, 0, "{platform}: {}", ui.err());
            downgrade(&legacy, &[&project]);

            let (code, ui) = run(&Request {
                uninstall: vec!["demo".to_string()],
                project: Some(project.clone()),
                ..Request::default()
            });

            assert_eq!(code, 0, "{platform} {legacy}: {}", ui.err());
            assert!(
                marked(&[&project]).is_empty(),
                "{platform} {legacy}: {:?}",
                marked(&[&project])
            );

            // The files it generated in the library's folder are its own, and go too.
            for path in files(&[&project]) {
                assert!(
                    !fs::read(&path).unwrap().starts_with(b"# Generated by"),
                    "{}",
                    path.display()
                );
            }
        }
    }
}

#[test]
fn each_file_is_saved_as_it_was_and_the_record_names_the_platform() {
    let root = tempfile::tempdir().unwrap();
    let project = project_of(root.path(), "zephyr", &[], true);
    let source = library_of(root.path(), "demo", "zephyr", DEFINE);

    assert_eq!(run(&asked_for(&project, &source, "zephyr")).0, 0);
    downgrade("zephyr-installer", &[&project]);

    let names = ["CMakeLists.txt", "prj.conf", ".zephyr-installer.json"];
    let before: Vec<Vec<u8>> = names
        .iter()
        .map(|name| fs::read(project.join(name)).unwrap())
        .collect();

    for path in fs::read_dir(&project).unwrap().flatten() {
        if path.file_name().to_string_lossy().ends_with(".bak") {
            fs::remove_file(path.path()).unwrap();
        }
    }

    let target = target_of(Platform::Zephyr, &PlatformArgs::default());
    let (moved, from) = migrate(&project, target.as_ref());
    let same = |path: &Path| dunce::canonicalize(path).unwrap();

    assert_eq!(from, "zephyr-installer");
    assert_eq!(
        moved.iter().map(|path| same(path)).collect::<Vec<_>>(),
        ["CMakeLists.txt", "prj.conf", ".libnima.json"].map(|name| same(&project.join(name)))
    );
    assert_eq!(record_file(&project)["platform"], "zephyr");

    for (name, held) in names.iter().zip(&before) {
        let saved = backups(&project, name);

        assert_eq!(saved.len(), 1, "{name}");
        assert_eq!(&fs::read(&saved[0]).unwrap(), held, "{name}");
    }

    // Once moved over, there is nothing more to move.
    assert!(migrate(&project, target.as_ref()).0.is_empty());
}

#[test]
fn markers_in_every_kconfig_file_of_zephyr_move_over() {
    let root = tempfile::tempdir().unwrap();
    let project = project_of(
        root.path(),
        "zephyr",
        &[("debug.conf", "CONFIG_DEBUG=y\n")],
        false,
    );
    let source = library_of(root.path(), "demo", "zephyr", "");
    let mut asked = request(&project, &[&source]);

    asked.args.conf = Some("debug.conf".to_string());
    assert_eq!(run(&asked).0, 0);

    let before = read(project.join("debug.conf"));

    downgrade("zephyr-installer", &[&project]);

    let (code, ui) = run(&request(&project, &[&source]));

    assert_eq!(code, 0, "{}", ui.err());
    assert_eq!(read(project.join("debug.conf")), before);
    assert!(!read(project.join("prj.conf")).contains("installer"));
}

#[test]
fn an_arduino_record_in_the_libraries_folder_moves_over() {
    for legacy in ["lib-installer", "arduino-installer"] {
        let root = tempfile::tempdir().unwrap();
        let project = project_of(root.path(), "arduino", &[], false);
        let book = root.path().join("Arduino");
        let libraries = book.join("libraries");
        let source = library_of(root.path(), "demo", "arduino", "");
        let mut asked = request(&project, &[&source]);

        fs::create_dir_all(&libraries).unwrap();
        asked.args.into = Some("libraries".to_string());
        asked.args.sketchbook = Some(book.to_string_lossy().into_owned());

        let (code, ui) = run(&asked);

        assert_eq!(code, 0, "{}", ui.err());

        let properties = fs::read(libraries.join("demo/library.properties")).unwrap();

        downgrade(legacy, &[&libraries]);

        let (code, ui) = run(&asked);

        assert_eq!(code, 0, "{}", ui.err());
        assert!(
            ui.out()
                .contains(&format!("Moved over from {legacy} to libnima")),
            "{}",
            ui.out()
        );
        assert_eq!(record_file(&libraries)["platform"], "arduino");
        assert!(!libraries.join(format!(".{legacy}.json")).exists());
        assert_eq!(
            fs::read(libraries.join("demo/library.properties")).unwrap(),
            properties
        );
    }
}

