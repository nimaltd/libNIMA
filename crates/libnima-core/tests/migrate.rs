#[test]
fn a_project_with_both_records_is_left_as_it_is() {
    let root = tempfile::tempdir().unwrap();
    let project = project_of(root.path(), "zephyr", &[], false);
    let source = library_of(root.path(), "demo", "zephyr", "");

    assert_eq!(run(&request(&project, &[&source])).0, 0);

    let old = "{\"record\": 2, \"libraries\": {}}";

    write(project.join(".zephyr-installer.json"), old);

    assert_eq!(run(&request(&project, &[&source])).0, 0);
    assert_eq!(read(project.join(".zephyr-installer.json")), old);
}

#[test]
fn a_marker_of_another_installer_is_left_alone() {
    let root = tempfile::tempdir().unwrap();
    let project = project_of(root.path(), "zephyr", &[], false);
    let source = library_of(root.path(), "demo", "zephyr", "");

    assert_eq!(run(&request(&project, &[&source])).0, 0);

    let cmake = project.join("CMakeLists.txt");

    write(
        &cmake,
        &format!("{}# >>> stm32-installer: x >>>\n", read(&cmake)),
    );
    downgrade("zephyr-installer", &[&project]);

    assert_eq!(run(&request(&project, &[&source])).0, 0);
    assert!(read(&cmake).contains("# >>> stm32-installer: x >>>"));
}
