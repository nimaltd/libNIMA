//! CMake projects, which covers VS Code and the CMake output of recent CubeMX.
//!
//! The library gets its own CMakeLists.txt holding its file list, and the project's
//! CMakeLists.txt gets two lines that never change no matter how many files the library
//! grows to.
//!
//! That library target is an INTERFACE library, not a STATIC one, and the difference is not
//! cosmetic. A driver's .c file includes main.h, which reaches the HAL headers, which need
//! the device macro and the driver include paths. CubeMX sets those on the executable
//! target, so a STATIC library would not see them and would fail to compile. An INTERFACE
//! library hands its sources to whoever links it, so they are compiled as part of the
//! application and inherit everything it has.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::LazyLock;

use regex::Regex;

use super::base::relative;
use crate::blocks;
use crate::files::{self, backup};
use crate::installer::Installed;
use crate::manifest::{MANIFEST_NAME, Manifest};
use crate::target::{Outcome, Status};
use crate::text::line_ending;

pub const NAME: &str = "CMake";

const LIBRARY_FILE: &str = "CMakeLists.txt";

/// add_executable(my_app ...) or add_library(my_lib ...)
static TARGET: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?m)^\s*add_(?:executable|library)\s*\(\s*([^\s)]+)").expect("a valid pattern")
});

/// CubeMX generated CMake projects define the target through the project() name.
static PROJECT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^\s*project\s*\(\s*([^\s)]+)").expect("a valid pattern"));

/// target_link_libraries(<target> <first thing after it>
static LINK_CALL: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"target_link_libraries\s*\(\s*([^\s)]+)\s+([^\s)]+)").expect("a valid pattern")
});

/// A block this tool wrote previously, so it can be ignored when reading the file.
static OWN_BLOCK: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?s)# >>> libnima:.*?# <<< libnima:[^\n]*\n?").expect("a valid pattern")
});

/// The first line of the CMakeLists.txt written into a library's folder, and what
/// lib-installer and stm32-installer wrote there before, still its own.
const GENERATED: [&str; 3] = [
    crate::MARK,
    "# Generated by lib-installer",
    "# Generated by stm32-installer",
];

const KEYWORDS: [&str; 3] = ["PRIVATE", "PUBLIC", "INTERFACE"];

/// What to call the generated library target.
///
/// Suffixed on purpose. A project is very often named after the library being tried out
/// in it, and CMake refuses to create two targets with one name. Testing fsm in a CubeMX
/// project called fsm is exactly how this shows up.
fn target_name(library: &str) -> String {
    format!("{library}_lib")
}

/// Whether this project already links libraries without a PRIVATE keyword.
///
/// CMake refuses to mix the plain and keyword forms on one target, and the CubeMX template
/// uses the plain one, so matching what is already there is not a matter of style. Getting
/// it wrong fails every CubeMX CMake project.
fn uses_plain_signature(text: &str) -> bool {
    // Blocks this tool wrote are skipped, or a second install would read its own keyword
    // form back and decide the project uses keywords.
    let own = OWN_BLOCK.replace_all(text, "");

    LINK_CALL
        .captures_iter(&own)
        .any(|found| !KEYWORDS.contains(&found[2].to_uppercase().as_str()))
}

/// The project's CMakeLists.txt, when this looks like a CMake project.
pub fn detect(project_root: &Path) -> Option<PathBuf> {
    let candidate = project_root.join("CMakeLists.txt");

    candidate.is_file().then_some(candidate)
}

/// The CMake target to attach the library to.
///
/// Prefers an explicit add_executable, since that is the firmware itself. Falls back to
/// ${CMAKE_PROJECT_NAME}, which is what the CubeMX template uses.
fn find_target(text: &str) -> Option<String> {
    if let Some(found) = TARGET.captures(text) {
        return Some(found[1].to_string());
    }

    PROJECT
        .is_match(text)
        .then(|| "${CMAKE_PROJECT_NAME}".to_string())
}

/// The CMakeLists.txt written into the library's own folder.
fn library_cmakelists(library: &Manifest) -> String {
    let target = target_name(&library.name);
    let listed: Vec<String> = library
        .build_sources()
        .iter()
        .map(|name| format!("    ${{CMAKE_CURRENT_SOURCE_DIR}}/{name}"))
        .collect();
    let includes: Vec<String> = library
        .include_dirs()
        .iter()
        .map(|dir| {
            if dir == "." {
                "${CMAKE_CURRENT_SOURCE_DIR}".to_string()
            } else {
                format!("${{CMAKE_CURRENT_SOURCE_DIR}}/{dir}")
            }
        })
        .collect();

    let label = format!("{} {}", library.name, library.version);
    let label = label.trim();

    // INTERFACE as well, so every file of the project is built with them, not only the
    // library's own. A define can change what the library's header declares, and a file
    // that saw a different one would disagree about it.
    let mut defines = String::new();

    if !library.defines.is_empty() {
        let listed_defines: Vec<String> = library
            .defines
            .iter()
            .map(|define| format!("    {define}"))
            .collect();
        defines = format!(
            "\ntarget_compile_definitions({target} INTERFACE\n{}\n)\n",
            listed_defines.join("\n")
        );
    }

    let name = &library.name;

    format!(
        "{mark} for {label}.\n\
         #\n\
         # INTERFACE, not STATIC, on purpose. These sources are compiled as part of your\n\
         # own target, so they inherit its defines and include paths. That is what lets\n\
         # the library's .c files find main.h and the HAL headers. A STATIC library would\n\
         # not see them and would fail to compile.\n\
         #\n\
         # The target is called {target} rather than {name}, because a project is often\n\
         # named after the library being tried out in it, and CMake allows only one\n\
         # target of a given name.\n\
         #\n\
         # This file is written again on every install and update, so a change made\n\
         # here does not last. The files come from the library's {MANIFEST_NAME}.\n\
         \n\
         add_library({target} INTERFACE)\n\
         \n\
         target_sources({target} INTERFACE\n\
         {listed}\n\
         )\n\
         \n\
         target_include_directories({target} INTERFACE {includes})\n\
         {defines}",
        mark = GENERATED[0],
        listed = listed.join("\n"),
        includes = includes.join(" "),
    )
}

/// The two lines this tool owns inside the user's CMakeLists.txt.
fn block(library: &str, folder: &str, plain: bool, target: &str, newline: &str) -> String {
    let found = blocks::Marker::new(library, None);
    let linked = target_name(library);
    let link = if plain {
        format!("target_link_libraries({target} {linked})")
    } else {
        format!("target_link_libraries({target} PRIVATE {linked})")
    };

    [
        found.open.as_str(),
        "# Added by libnima. Delete this block to drop the library from",
        &format!("# the build. Its file list lives in {folder}/{LIBRARY_FILE}."),
        &format!("add_subdirectory({folder})"),
        &link,
        found.close.as_str(),
    ]
    .join(newline)
}

/// Give the library its own CMakeLists.txt, then point the project at it.
///
/// What an update dropped needs nothing here: the library's CMakeLists.txt is written again
/// from the new manifest on every install, so a file or a define that has gone is simply
/// no longer in it.
pub fn integrate(
    cmakelists: &Path,
    library: &Manifest,
    destination: &Path,
    project_root: &Path,
) -> io::Result<Outcome> {
    let name = cmakelists
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let folder = relative(destination, project_root);
    let manual = || manual_steps(&folder, &library.name);

    let text = match fs::read(cmakelists) {
        Ok(bytes) => String::from_utf8(bytes)
            .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?,
        Err(error) => {
            return Ok(Outcome::new(
                NAME,
                Status::Manual,
                format!("Could not read {name}: {}", files::reason(&error)),
            )
            .with_steps(manual()));
        }
    };

    let Some(target) = find_target(&text) else {
        return Ok(Outcome::new(
            NAME,
            Status::Manual,
            format!("Could not find an add_executable or project call in {name}."),
        )
        .with_steps(manual()));
    };

    // Written every time, so adding a source file to a library reaches everyone who
    // updates, without them editing anything.
    if let Err(error) = files::write(
        &destination.join(LIBRARY_FILE),
        &library_cmakelists(library),
    ) {
        return Ok(Outcome::new(
            NAME,
            Status::Manual,
            format!(
                "Could not write {folder}/{LIBRARY_FILE}: {}",
                files::reason(&error)
            ),
        )
        .with_steps(manual()));
    }

    let newline = line_ending(&text);

    // Built with the line ending the file already uses, and before the block is compared
    // with the one already in the file. Comparing a block built with line feeds against a
    // stored block written with CRLF never matches, and the integration would rewrite the
    // file and take a backup on every single run.
    let written = block(
        &library.name,
        &folder,
        uses_plain_signature(&text),
        &target,
        newline,
    );
    let found = blocks::Marker::new(&library.name, None);

    let Ok(span) = blocks::span(&text, &found) else {
        return Ok(Outcome::new(
            NAME,
            Status::Manual,
            format!("{name} has a half written libnima block. Fix it by hand first."),
        )
        .with_steps(manual()));
    };

    let record_name = relative(cmakelists, project_root);
    let updated = match span {
        Some((start, end)) => {
            if text[start..end] == written {
                return Ok(Outcome::new(
                    NAME,
                    Status::Already,
                    format!("{name} already has {}.", library.name),
                )
                .with_blocks(record_name, blocks::fingerprints(&text, &[found])));
            }

            format!("{}{written}{}", &text[..start], &text[end..])
        }
        None => blocks::appended(&text, &written, newline),
    };

    let saved = backup(cmakelists)?;

    if let Err(error) = files::write(cmakelists, &updated) {
        return Ok(Outcome::new(
            NAME,
            Status::Manual,
            format!("Could not write {name}: {}", files::reason(&error)),
        )
        .with_steps(manual())
        .with_backup(Some(saved)));
    }

    Ok(Outcome::new(
        NAME,
        Status::Changed,
        format!("Added {} to {name}, linked to {target}.", library.name),
    )
    .with_backup(Some(saved))
    .with_blocks(record_name, blocks::fingerprints(&updated, &[found])))
}

/// What to paste in, when this could not do it safely.
pub fn manual_steps(folder: &str, library: &str) -> Vec<String> {
    vec![
        "Add this to your CMakeLists.txt, using your own target name:".to_string(),
        format!("add_subdirectory({folder})"),
        format!(
            "target_link_libraries(your_target PRIVATE {})",
            target_name(library)
        ),
        "Drop the PRIVATE if your project links libraries without it.".to_string(),
    ]
}

/// Take the library's block out of the project's CMakeLists.txt, and the CMakeLists.txt
/// written into its folder with it.
pub fn remove(cmakelists: &Path, library: &Installed) -> io::Result<Outcome> {
    let name = cmakelists
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let text = files::read(cmakelists)?;

    if let Some(destination) = &library.destination {
        let own = destination.join(LIBRARY_FILE);

        if own.is_file()
            && files::read(&own)
                .is_ok_and(|text| GENERATED.iter().any(|mark| text.starts_with(mark)))
        {
            fs::remove_file(own)?;
        }
    }

    let found = blocks::Marker::new(&library.name, None);

    match blocks::span(&text, &found) {
        Ok(None) => Ok(Outcome::new(
            NAME,
            Status::Already,
            format!("{name} has nothing of {}.", library.name),
        )),
        Err(_) => Ok(Outcome::new(
            NAME,
            Status::Manual,
            format!(
                "{name} has a half written libnima block for {}. Take it out by hand.",
                library.name
            ),
        )),
        Ok(Some(span)) => {
            // The line ending after the block, and the blank line the install brought.
            let saved = backup(cmakelists)?;
            files::write(cmakelists, &blocks::cut(&text, span, line_ending(&text)))?;

            Ok(Outcome::new(
                NAME,
                Status::Changed,
                format!("Removed {} from {name}.", library.name),
            )
            .with_backup(Some(saved)))
        }
    }
}
