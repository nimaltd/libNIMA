/// The version of libNIMA, kept in the workspace's `Cargo.toml`.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Where a newer libNIMA is to be had.
pub const RELEASES_PAGE: &str = "https://github.com/nimaltd/libNIMA/releases/latest";

/// The first line of a file libNIMA writes into a library's folder, so a file of the library's
/// own is never mistaken for one this wrote.
pub const MARK: &str = "# Generated by libnima";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_version_has_three_numbers() {
        let parts: Vec<&str> = VERSION.split('.').collect();
        assert_eq!(parts.len(), 3, "{VERSION}");
        assert!(
            parts.iter().all(|part| part.parse::<u32>().is_ok()),
            "{VERSION}"
        );
    }
}
